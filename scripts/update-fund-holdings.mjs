import { readFile, writeFile, rename, unlink } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { randomUUID } from "node:crypto";
import { fetchVanguardFund, normalizeVanguardFund } from "../js/data/vanguard-holdings.js";

export async function updateFundHoldings({ fetchImpl, previous, now = Date.now() } = {}) {
  const retained = normalizeVanguardFund(previous, {now});
  try {
    const latest = await fetchVanguardFund({fetchImpl,now,timeoutMs:15000});
    return { fund: retained?.asOf > latest.asOf ? retained : latest, retained: retained?.asOf > latest.asOf };
  } catch {
    if(retained)return {fund:retained,retained:true};
    throw new Error("No recent complete Vanguard stock holdings are available.");
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const path=resolve(import.meta.dirname,"../js/data/fund-holdings-snapshot.js");
  let previous=null;
  try { previous=JSON.parse((await readFile(path,"utf8")).match(/export default ([\s\S]*);\s*$/)[1]); } catch { /* First publication. */ }
  const result=await updateFundHoldings({previous});
  const temporary=`${path}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary,`// Public issuer holdings. Generated by scripts/update-fund-holdings.mjs.\nexport default ${JSON.stringify(result.fund)};\n`);
    await rename(temporary,path);
  } finally { await unlink(temporary).catch(()=>{}); }
  console.log(`${result.retained ? "Retained" : "Published"} ${result.fund.securityCount} Vanguard securities / ${result.fund.holdings.length} companies, ${(result.fund.coverage*100).toFixed(2)}% coverage, as of ${result.fund.asOf}.`);
}
